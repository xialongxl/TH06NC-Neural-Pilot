def serialized_row(row):
    return {key: json.dumps(value, ensure_ascii=False, default=_json_default) if isinstance(value,(dict,list,tuple)) else value for key,value in row.items()}


def episode_row(info, steps, elapsed=None):
    diagnostics = info.get('episode_diagnostics',{})
    return {'steps':int(steps),'elapsed_seconds':elapsed,'survival_seconds':info.get('survival_seconds',0),
            'game_settings':info.get('game_settings'),
            'died':bool(info.get('died')),'episode_end_reason':info.get('episode_end_reason'),
            'reward_version':info.get('reward_version',REWARD_VERSION),
            'stage_id':info.get('stage_id',diagnostics.get('stage_id')),
            'stage_label':info.get('stage_label',diagnostics.get('stage_label')),
            'stage_seconds':info.get('stage_seconds',diagnostics.get('stage_seconds')),
            'stage_changes':info.get('stage_changes',diagnostics.get('stage_changes')),
            'death_id':info.get('death_id'),'goal':info.get('goal'),
            'bombs_used':info.get('episode_bombs_used',0),
            'nmnb_clean_so_far':not bool(info.get('died')) and not info.get('episode_bombs_used',0),
            **{name:diagnostics.get(name,0.) for name in DIAGNOSTIC_FIELDS}}
